"""Versioned, verified release bundles and immutable GitHub publication.

Generated by ci/apply.py from agentic-workspace; configuration is read from
.github/cicd.json, never hardcoded here.
"""
import argparse
from datetime import date
import gzip
import hashlib
import io
import json
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import tarfile
import urllib.error
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SEMVER = r'(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)'


def load_config(root=ROOT):
    return json.loads((root / '.github/cicd.json').read_text())


CONFIG = load_config()
REPOSITORY = CONFIG['repository']
PROJECT = CONFIG['project']
TAG_PREFIX = CONFIG.get('tag_prefix', '')


def tag_for(version):
    return TAG_PREFIX + version


def fingerprint(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            digest.update(chunk)
    return {'bytes': Path(path).stat().st_size, 'sha256': digest.hexdigest()}


def safe_path(name):
    path = PurePosixPath(name)
    if path.is_absolute() or '..' in path.parts or not path.parts or '\\' in name:
        raise ValueError('Unsafe release path: ' + name)
    return path


def release_version(root=ROOT):
    config = load_config(root)
    text = (root / config['version_file']).read_text()
    match = re.search(config['version_regex'], text, re.M)
    if not match or not re.fullmatch(SEMVER, match.group('v')):
        raise ValueError(config['version_file'] + ' must contain a plain MAJOR.MINOR.PATCH version.')
    version = match.group('v')
    notes = (root / config['changelog']).read_text()
    heading = re.search(r'^## \[' + re.escape(version) + r'\] - (\d{4}-\d{2}-\d{2})$', notes, re.M)
    if not heading:
        raise ValueError('The release needs a dated "## [X.Y.Z] - YYYY-MM-DD" changelog entry.')
    date.fromisoformat(heading[1])
    return version


def release_notes(version, root=ROOT):
    notes = (root / load_config(root)['changelog']).read_text()
    match = re.search(r'^## \[' + re.escape(version) + r'\].*?\n(.*?)(?=^## |\Z)', notes, re.M | re.S)
    if not match or not match[1].strip():
        raise ValueError('Release notes are empty.')
    return match[1].strip()


def source_sha():
    value = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    if not re.fullmatch(r'[0-9a-f]{40}', value):
        raise ValueError('Invalid source revision.')
    if os.environ.get('GITHUB_EVENT_NAME') == 'pull_request':
        # PR jobs check out the proposed head, not GitHub's synthetic merge ref.
        event = json.loads(Path(os.environ['GITHUB_EVENT_PATH']).read_text())
        pull = event.get('pull_request', {})
        if (os.environ.get('GITHUB_REPOSITORY') != REPOSITORY
                or pull.get('base', {}).get('repo', {}).get('full_name') != REPOSITORY
                or pull.get('head', {}).get('sha') != value):
            raise ValueError('Checked-out source differs from the validated PR head.')
    elif os.environ.get('GITHUB_SHA', value) != value:
        raise ValueError('Checked-out source differs from workflow source.')
    return value


def site_files(directory):
    directory = Path(directory)
    if not directory.is_dir():
        raise ValueError(f'Build output {directory} does not exist; run the build first.')
    files = {}
    for path in sorted(directory.rglob('*')):
        if path.is_symlink():
            raise ValueError('Symbolic links are not allowed in release output.')
        if path.is_file():
            files[safe_path(path.relative_to(directory).as_posix()).as_posix()] = fingerprint(path)
    if not files:
        raise ValueError('Build output is empty.')
    return files


def archive_site(directory, target):
    directory = Path(directory)
    with Path(target).open('wb') as raw, gzip.GzipFile(fileobj=raw, mode='wb', filename='', mtime=0) as zipped:
        with tarfile.open(fileobj=zipped, mode='w', format=tarfile.PAX_FORMAT) as archive:
            for name in site_files(directory):
                data = (directory / name).read_bytes()
                info = tarfile.TarInfo(name)
                info.size, info.mtime, info.mode, info.uid, info.gid = len(data), 0, 0o644, 0, 0
                archive.addfile(info, io.BytesIO(data))


def write_identity(output, identity):
    output = Path(output)
    (output / 'release-identity.json').write_text(json.dumps(identity, indent=2, sort_keys=True) + '\n')
    names = sorted(p.name for p in output.iterdir() if p.is_file() and p.name != 'SHA256SUMS')
    (output / 'SHA256SUMS').write_text(''.join(
        f'{fingerprint(output / name)["sha256"]}  {name}\n' for name in names))


def prepare(directory=None, output=ROOT / 'build/release'):
    directory = Path(directory or ROOT / CONFIG['artifact_dir'])
    version, sha = release_version(), source_sha()
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    for stale in output.iterdir():
        if stale.is_file():
            stale.unlink()
    files = site_files(directory)
    archive = output / f'{PROJECT}-{version}.tar.gz'
    archive_site(directory, archive)
    (output / 'release-notes.md').write_text(
        release_notes(version) + f'\n\nSource: {REPOSITORY}@{sha}\n')
    write_identity(output, {
        'project': PROJECT, 'repository': REPOSITORY, 'version': version, 'tag': tag_for(version),
        'source_sha': sha, 'files': files, 'artifacts': {archive.name: fingerprint(archive)}})
    print(f'Prepared {PROJECT} {version} with {len(files)} files.')


def verify_bundle(output, extract=None, require_container=False):
    output = Path(output)
    identity = json.loads((output / 'release-identity.json').read_text())
    if not re.fullmatch(SEMVER, identity.get('version', '')) or identity.get('repository') != REPOSITORY:
        raise ValueError('Release identity is invalid.')
    if require_container and 'container_id' not in identity:
        raise ValueError('Release identity lacks the built container.')
    for name, expected in identity['artifacts'].items():
        safe_path(name)
        if fingerprint(output / name) != expected:
            raise ValueError(f'Artifact {name} differs from the approved bytes.')
    sums = (output / 'SHA256SUMS').read_text()
    for name, expected in identity['artifacts'].items():
        if f'{expected["sha256"]}  {name}\n' not in sums:
            raise ValueError('SHA256SUMS does not cover every artifact.')
    archive = output / f'{PROJECT}-{identity["version"]}.tar.gz'
    seen = {}
    with tarfile.open(archive, 'r:gz') as tar:
        for member in tar.getmembers():
            if not member.isfile():
                raise ValueError('Release archive may contain only regular files.')
            name = safe_path(member.name).as_posix()
            data = tar.extractfile(member).read()
            seen[name] = {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
            if extract is not None:
                target = Path(extract) / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
    if seen != identity['files']:
        raise ValueError('Release archive contents differ from the identity manifest.')
    return identity


def release_plan(version, sha, tag, existing, expected):
    name = tag_for(version)
    if tag is not None:
        obj = tag.get('object', {})
        if obj.get('type') != 'commit' or obj.get('sha') != sha:
            raise ValueError('Existing tag conflicts with source; tags are immutable.')
    if existing is None:
        return sorted(expected)
    if (tag is None or existing.get('tag_name') != name
            or f'Source: {REPOSITORY}@{sha}' not in existing.get('body', '')):
        raise ValueError('Existing release identity conflicts.')
    present = set()
    for asset in existing.get('assets', []):
        asset_name = asset.get('name')
        if (asset_name in present or asset_name not in expected or asset.get('state') != 'uploaded'
                or asset.get('size') != expected[asset_name]['bytes']
                or asset.get('digest') != 'sha256:' + expected[asset_name]['sha256']):
            raise ValueError('Existing release asset differs; never replace assets.')
        present.add(asset_name)
    missing = sorted(set(expected) - present)
    if missing and not existing.get('draft'):
        raise ValueError('Published releases cannot be extended or replaced.')
    return missing


def api(path, data=None, method='GET', optional=False, binary=None):
    host = 'https://uploads.github.com' if binary is not None else 'https://api.github.com'
    payload = binary if binary is not None else (json.dumps(data).encode() if data is not None else None)
    request = urllib.request.Request(host + path, data=payload, method=method, headers={
        'Authorization': 'Bearer ' + os.environ['GITHUB_TOKEN'],
        'Accept': 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28',
        'Content-Type': 'application/octet-stream' if binary is not None else 'application/json',
    })
    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        if optional and error.code == 404:
            return None
        raise RuntimeError(f'GitHub operation failed (HTTP {error.code}); inspect the run before retrying.') from None


def find_release(base, tag_name, request=api):
    # The tag lookup can omit a draft, so also list releases before creating anything.
    direct = request(base + '/releases/tags/' + tag_name, optional=True)
    matches = {} if direct is None else {direct['id']: direct}
    for page in range(1, 11):
        releases = request(base + f'/releases?per_page=100&page={page}')
        if not isinstance(releases, list):
            raise ValueError('Invalid authenticated release listing.')
        for release in releases:
            if release.get('tag_name') == tag_name:
                matches[release['id']] = release
        if len(matches) > 1:
            raise ValueError('Multiple releases share this tag; inspect instead of creating or replacing.')
        if len(releases) < 100:
            return next(iter(matches.values()), None)
    raise ValueError('Release listing exceeded its safety bound; cannot infer absence.')


def publish(output, apply=False):
    identity = verify_bundle(output, require_container=bool(CONFIG['features'].get('container')))
    version, sha = identity['version'], identity['source_sha']
    name = tag_for(version)
    base = '/repos/' + REPOSITORY
    tag = api(base + '/git/ref/tags/' + name, optional=True)
    existing = find_release(base, name, api)
    expected = {p.name: fingerprint(p) for p in Path(output).iterdir() if p.is_file()}
    allowed = set(identity['artifacts']) | {'release-identity.json', 'SHA256SUMS', 'release-notes.md'}
    if set(expected) != allowed:
        raise ValueError('Unexpected file in release bundle.')
    if existing is not None:
        existing['assets'] = api(base + f'/releases/{existing["id"]}/assets?per_page=100')
    missing = release_plan(version, sha, tag, existing, expected)
    if not apply:
        print(f'Release preflight passed; {len(missing)} immutable assets remain to upload.')
        return
    import release_guard
    release_guard.approval()
    if tag is None:
        api(base + '/git/refs', {'ref': 'refs/tags/' + name, 'sha': sha}, method='POST')
    if existing is None:
        existing = api(base + '/releases', {'tag_name': name, 'target_commitish': sha, 'name': name,
                       'draft': True, 'prerelease': False,
                       'body': (Path(output) / 'release-notes.md').read_text()}, method='POST')
    for asset in missing:
        result = api(base + f'/releases/{existing["id"]}/assets?name=' + urllib.parse.quote(asset),
                     method='POST', binary=(Path(output) / asset).read_bytes())
        if result.get('digest') != 'sha256:' + expected[asset]['sha256']:
            raise ValueError('Uploaded asset digest differs; release remains a draft.')
    # Long uploads must not outlive source or approval-policy changes.
    release_guard.approval()
    if existing.get('draft'):
        api(base + f'/releases/{existing["id"]}', {'name': name, 'draft': False, 'make_latest': 'true'},
            method='PATCH')
    print(f'Immutable release {name} is published.')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('command', choices=['version', 'prepare', 'verify', 'preflight', 'publish'])
    parser.add_argument('--directory', type=Path, default=ROOT / 'build/release')
    parser.add_argument('--extract', type=Path)
    args = parser.parse_args()
    if args.command == 'version':
        print(release_version())
    elif args.command == 'prepare':
        prepare(output=args.directory)
    elif args.command == 'verify':
        verify_bundle(args.directory, args.extract,
                      require_container=bool(CONFIG['features'].get('container')))
        print('Release artifact identity and checksums verified.')
    else:
        publish(args.directory, apply=args.command == 'publish')


if __name__ == '__main__':
    main()
